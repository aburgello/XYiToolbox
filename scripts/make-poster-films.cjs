#!/usr/bin/env node
/**
 * Generates src/js/main/arcade/films.ts -- the POSTER game's answer list.
 *
 * WHY A GENERATED, COMMITTED LIST rather than fetching the film of the day at
 * runtime: the daily puzzle has to be the SAME FILM on every machine with no
 * server and no coordination (the same free-sync trick DAILY uses for words).
 * Deriving it from a live TMDB query can't guarantee that -- `discover`'s
 * ordering shifts as vote counts move, so two people opening the panel a day
 * apart could be handed different films and the board would be nonsense. A
 * committed list makes the answer a pure function of the date.
 *
 * Same source as the XYiNerdle starting pool (see arcade/cine/tmdb.ts for the
 * reasoning): `discover` sorted by vote_count DESC, NOT `/movie/popular` --
 * "popular" means popular right now and comes back entirely from the current
 * year. Most-rated is a decent proxy for most widely recognised, and spans
 * decades. Documentaries and TV movies are excluded (nobody could place their
 * posters), as is anything with no poster -- a poster game needs a poster.
 *
 * Run: node scripts/make-poster-films.cjs
 * Re-run to refresh/extend the list. NEVER hand-edit films.ts -- same rule as
 * arcade/guessWords.ts.
 */
const fs = require("fs");
const path = require("path");
const https = require("https");

const KEY = "0edca0cf8b6cba2aec8b2f7a07e50fea";
const PAGES = 30; // x20 results = ~600 films = ~1.6 years of dailies

const get = (url) =>
    new Promise((resolve, reject) => {
        https
            .get(url, (res) => {
                let body = "";
                res.on("data", (c) => (body += c));
                res.on("end", () => {
                    try {
                        resolve(JSON.parse(body));
                    } catch (e) {
                        reject(e);
                    }
                });
            })
            .on("error", reject);
    });

(async () => {
    const films = [];
    const seen = new Set();
    for (let page = 1; page <= PAGES; page++) {
        const url =
            "https://api.themoviedb.org/3/discover/movie?sort_by=vote_count.desc" +
            "&vote_count.gte=1000&without_genres=99,10770&include_adult=false&page=" +
            page +
            "&api_key=" +
            KEY;
        const data = await get(url);
        for (const m of data.results || []) {
            if (!m.poster_path || !m.release_date || seen.has(m.id)) continue;
            seen.add(m.id);
            films.push({ id: m.id, t: m.title, y: m.release_date.slice(0, 4), p: m.poster_path });
        }
        process.stderr.write(`page ${page}: ${films.length} films\n`);
    }

    // Sorted by id so the list is stable across regenerations: a re-run that
    // adds films doesn't reshuffle which day gets which existing film any more
    // than it has to.
    films.sort((a, b) => a.id - b.id);

    const out =
        `// GENERATED by scripts/make-poster-films.cjs -- do not hand-edit.\n` +
        `//\n` +
        `// The POSTER game's answer list: ${films.length} widely-known films, most-rated\n` +
        `// first from TMDB's discover endpoint. See the script's header for why this is\n` +
        `// committed rather than fetched (the daily answer must be a pure function of\n` +
        `// the date, identical on every machine, with no server).\n` +
        `//\n` +
        `// Fields are short on purpose -- this ships in the panel bundle.\n` +
        `//   id = TMDB movie id, t = title, y = year, p = poster path\n` +
        `export interface PosterFilm {\n` +
        `    id: number;\n` +
        `    t: string;\n` +
        `    y: string;\n` +
        `    p: string;\n` +
        `}\n\n` +
        `export const FILMS: PosterFilm[] = [\n` +
        films
            .map((f) => `    { id: ${f.id}, t: ${JSON.stringify(f.t)}, y: "${f.y}", p: "${f.p}" },`)
            .join("\n") +
        `\n];\n`;

    const target = path.join(__dirname, "..", "src", "js", "main", "arcade", "films.ts");
    fs.writeFileSync(target, out);
    process.stderr.write(`wrote ${films.length} films -> ${target}\n`);
})();
